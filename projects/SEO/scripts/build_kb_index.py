# 1. Gather all file metadata
def get_file_meta(path):
    if not os.path.exists(path):
        return None
    st = os.stat(path)
    dt = datetime.fromtimestamp(st.st_mtime).strftime('%Y-%m-%d %H:%M:%S')
    return {
        "name": os.path.basename(path),
        "path": path,
        "size_kb": round(st.st_size / 1024, 1),
        "mtime": dt
    }

