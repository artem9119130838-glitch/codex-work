def inspect_large_drawing(img_path, out_dir=r'C:\Codex\scratch'):
    os.makedirs(out_dir, exist_ok=True)
    if not os.path.exists(img_path):
        print(f'Error: Image not found: {img_path}')
        return
    im = Image.open(img_path)
    w, h = im.size
    print(f'Loaded image {img_path}: {w}x{h} ({w*h/1e6:.1f} MP)')

    base_name = os.path.splitext(os.path.basename(img_path))[0]
    # Crop technical notes (lower right above title block)
    crop_notes = im.crop((int(w * 0.55), int(h * 0.45), w, h))
    notes_path = os.path.join(out_dir, f'{base_name}_notes.jpg')
    crop_notes.save(notes_path, quality=85)

    # Preview resized
    ratio = 2500 / w
    preview = im.resize((2500, int(h * ratio)), Image.Resampling.LANCZOS)
    preview_path = os.path.join(out_dir, f'{base_name}_preview.jpg')
    preview.save(preview_path, quality=85)
    print(f'Saved preview: {preview_path} and notes: {notes_path}')

def extract_pdf_scans(pdf_path, out_dir=r'C:\Codex\scratch\pdf_pages'):
    import pypdf
    os.makedirs(out_dir, exist_ok=True)
    if not os.path.exists(pdf_path):
        print(f'Error: PDF not found: {pdf_path}')
        return
    reader = pypdf.PdfReader(pdf_path)
    print(f'Extracting {len(reader.pages)} pages from {pdf_path}...')
    for i, page in enumerate(reader.pages):
        for j, img in enumerate(page.images):
            img_path = os.path.join(out_dir, f'page_{i+1}_img_{j+1}.jpg')
            with open(img_path, 'wb') as f:
                f.write(img.data)
            print(f'Extracted: {img_path}')

